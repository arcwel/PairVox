#!/usr/bin/env python3
"""Regenerates Sources/PairVoxVoice/WhisperPins.swift: the exact Hugging Face commits, file sizes and SHA-256
hashes of the Whisper models (and tokenizers) PairVox offers. PairVox downloads only these, at these commits,
and refuses anything that does not hash to the pinned value.

  scripts/pin-whisper-models.py            rewrite the file at the repository's current upstream commits
  scripts/pin-whisper-models.py --check    exit 1 if upstream has moved past the pinned commits (informational)
"""
import hashlib, json, sys, urllib.request, pathlib

MODEL_REPO = "argmaxinc/whisperkit-coreml"
VARIANTS = {  # variant folder -> tokenizer repo WhisperKit would otherwise fetch
    "openai_whisper-base.en": "openai/whisper-base.en",
    "openai_whisper-small.en": "openai/whisper-small.en",
    "distil-whisper_distil-large-v3_turbo": "openai/whisper-large-v3",
}
TOKENIZER_FILES = ["tokenizer.json", "tokenizer_config.json", "config.json"]
OUT = pathlib.Path(__file__).resolve().parent.parent / "Sources/PairVoxVoice/WhisperPins.swift"


def get(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "pairvox-pin"})).read()


def api(path):
    return json.loads(get("https://huggingface.co/api/" + path))


def sha256_of(repo, commit, path):
    data = get(f"https://huggingface.co/{repo}/resolve/{commit}/{path}")
    return hashlib.sha256(data).hexdigest(), len(data)


def entries(repo, commit, prefix, only=None):
    tree = api(f"models/{repo}/tree/{commit}" + (f"/{prefix}" if prefix else "") + "?recursive=true")
    out = []
    for item in sorted((t for t in tree if t["type"] == "file"), key=lambda t: t["path"]):
        rel = item["path"][len(prefix) + 1:] if prefix else item["path"]
        if only and rel not in only:
            continue
        if "lfs" in item:
            digest, size = item["lfs"]["oid"], item["size"]
        else:
            digest, size = sha256_of(repo, commit, item["path"])
        out.append((rel, size, digest))
    return out


def main():
    check = "--check" in sys.argv
    commits = {MODEL_REPO: api(f"models/{MODEL_REPO}")["sha"]}
    for tok in set(VARIANTS.values()):
        commits[tok] = api(f"models/{tok}")["sha"]
    if check:
        text = OUT.read_text()
        stale = [r for r, c in commits.items() if c not in text]
        print("upstream has moved:" if stale else "pins are current", ", ".join(stale))
        sys.exit(1 if stale else 0)
    lines = ["// SPDX-License-Identifier: Apache-2.0", "",
             "// Generated by scripts/pin-whisper-models.py. Do not edit by hand.", "",
             "enum WhisperPins {",
             "    struct File { let path: String; let bytes: Int64; let sha256: String }",
             "    struct Pin { let repo: String; let commit: String; let folder: String; let files: [File] }",
             "    struct Variant { let model: Pin; let tokenizer: Pin }", "",
             "    static let variants: [String: Variant] = ["]
    for variant, tok_repo in VARIANTS.items():
        m = entries(MODEL_REPO, commits[MODEL_REPO], variant)
        t = entries(tok_repo, commits[tok_repo], "", only=set(TOKENIZER_FILES))
        missing = set(TOKENIZER_FILES) - {p for p, _, _ in t}
        if "tokenizer.json" in missing:
            sys.exit(f"{tok_repo} has no tokenizer.json")
        def pin(repo, folder, files):
            body = ",\n".join(f'                File(path: "{p}", bytes: {s}, sha256: "{h}")' for p, s, h in files)
            return (f'Pin(repo: "{repo}", commit: "{commits[repo]}", folder: "{folder}", files: [\n{body},\n            ])')
        lines.append(f'        "{variant}": Variant(')
        lines.append(f'            model: {pin(MODEL_REPO, variant, m)},')
        lines.append(f'            tokenizer: {pin(tok_repo, "", t)}),')
    lines += ["    ]", "}", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({sum(len(v) for v in [VARIANTS])} variants)")


main()
